"""`TriMesh` は numpy の頂点 (N,3) と面 (M,3) だけを持つ。ピースの殻は個別に閉じている
ことを `check_closed` で検査する (全有向辺がちょうど 1 回ずつ、かつ逆向きの辺も 1 回 =
向きの揃った閉多様体)。ボクセライザ (TriBoxOverlap + flood-fill) は面の向きを見ないが、
閉じていない殻は内部が埋まらないので「閉じていること」だけは生成側で保証する。

2D 多角形の符号付き距離 (`polygon_sdf`) もここに置く。回転体の (r,z) 断面と凸角柱の
断面の両方がこれを使う (2 本目を書かない)。
"""
from dataclasses import dataclass
from pathlib import Path

import numpy as np

DEGENERATE_AREA = 1e-12


@dataclass
class TriMesh:
    verts: np.ndarray  # float64 (N,3)
    faces: np.ndarray  # int64 (M,3)

    @property
    def tri_count(self) -> int:
        return int(self.faces.shape[0])

    def transformed(self, R: np.ndarray, t) -> "TriMesh":
        """world = R @ local + t。"""
        verts = self.verts @ np.asarray(R, dtype=np.float64).T + np.asarray(t, dtype=np.float64)
        return TriMesh(verts, self.faces.copy())

    def aabb(self):
        return self.verts.min(axis=0), self.verts.max(axis=0)

    def longest_edge(self) -> float:
        lo, hi = self.aabb()
        return float(np.max(hi - lo))


def concat(meshes) -> TriMesh:
    verts = []
    faces = []
    base = 0
    for m in meshes:
        verts.append(m.verts)
        faces.append(m.faces + base)
        base += m.verts.shape[0]
    if not verts:
        return TriMesh(np.zeros((0, 3)), np.zeros((0, 3), dtype=np.int64))
    return TriMesh(np.vstack(verts), np.vstack(faces))


@dataclass
class ClosedReport:
    ok: bool
    reason: str
    vertex_count: int
    edge_count: int
    face_count: int

    @property
    def euler(self) -> int:
        return self.vertex_count - self.edge_count + self.face_count


def check_closed(mesh: TriMesh) -> ClosedReport:
    """閉じた向き付き殻か。退化三角形 (面積 < DEGENERATE_AREA) も不合格にする。
    有向辺 (a,b) を数え、全辺が「(a,b) 1 回 + (b,a) 1 回」であること。"""
    v = mesh.verts
    f = mesh.faces
    nv, nf = int(v.shape[0]), int(f.shape[0])
    if nf == 0:
        return ClosedReport(False, "no faces", nv, 0, 0)
    if np.any(f < 0) or np.any(f >= nv):
        return ClosedReport(False, "face index out of range", nv, 0, nf)
    a, b, c = v[f[:, 0]], v[f[:, 1]], v[f[:, 2]]
    area2 = np.linalg.norm(np.cross(b - a, c - a), axis=1)
    if np.any(area2 < 2.0 * DEGENERATE_AREA):
        return ClosedReport(False, "degenerate triangle", nv, 0, nf)
    if np.any((f[:, 0] == f[:, 1]) | (f[:, 1] == f[:, 2]) | (f[:, 2] == f[:, 0])):
        return ClosedReport(False, "repeated vertex in face", nv, 0, nf)

    directed = np.vstack([f[:, [0, 1]], f[:, [1, 2]], f[:, [2, 0]]]).astype(np.int64)
    keys = directed[:, 0] * nv + directed[:, 1]
    uniq, counts = np.unique(keys, return_counts=True)
    if np.any(counts != 1):
        return ClosedReport(False, "directed edge used more than once", nv, int(uniq.size), nf)
    reverse = directed[:, 1] * nv + directed[:, 0]
    if not np.all(np.isin(reverse, uniq, assume_unique=False)):
        return ClosedReport(False, "boundary edge (not closed)", nv, int(uniq.size), nf)
    return ClosedReport(True, "", nv, int(uniq.size) // 2, nf)


def fan_triangulate(indices):
    """凸多角形 (頂点 index 列、順序どおり) を扇状に三角形化する。"""
    return [(indices[0], indices[i], indices[i + 1]) for i in range(1, len(indices) - 1)]


def write_obj(path, mesh: TriMesh, header_lines=()):
    """`v`/`f` だけの ASCII OBJ。先頭に来歴コメントを書く (TriangleSoup.cpp の最小リーダは
    `#` 以降を落とすので安全)。座標は 5 桁 (設計空間は主寸法 1.0 なので 1e-5 ≪ h/28)。"""
    lines = [f"# {line}" for line in header_lines]
    lines.append("# generated by DeepModalModel/shapegen (do not edit by hand)")
    for x, y, z in mesh.verts:
        lines.append(f"v {x:.5f} {y:.5f} {z:.5f}")
    for a, b, c in mesh.faces:
        lines.append(f"f {int(a) + 1} {int(b) + 1} {int(c) + 1}")
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


# ---- 2D 多角形 ----

def polygon_area(poly) -> float:
    """符号付き面積 (CCW で正)。"""
    p = np.asarray(poly, dtype=np.float64)
    x, y = p[:, 0], p[:, 1]
    return 0.5 * float(np.sum(x * np.roll(y, -1) - np.roll(x, -1) * y))


def polygon_centroid(poly):
    p = np.asarray(poly, dtype=np.float64)
    x, y = p[:, 0], p[:, 1]
    xn, yn = np.roll(x, -1), np.roll(y, -1)
    cross = x * yn - xn * y
    a = 0.5 * np.sum(cross)
    if abs(a) < 1e-15:
        return float(np.mean(x)), float(np.mean(y))
    cx = np.sum((x + xn) * cross) / (6.0 * a)
    cy = np.sum((y + yn) * cross) / (6.0 * a)
    return float(cx), float(cy)


def polygon_sdf(points, poly) -> np.ndarray:
    """多角形 (単純、向き不問) に対する符号付き距離。内側が負。
    points (N,2)、poly (M,2)。辺ごとの距離の最小 + 偶奇規則の符号 (Inigo Quilez の式)。"""
    p = np.asarray(points, dtype=np.float64)
    v = np.asarray(poly, dtype=np.float64)
    n = v.shape[0]
    d = np.full(p.shape[0], np.inf)
    inside = np.zeros(p.shape[0], dtype=bool)
    for i in range(n):
        a = v[i]
        b = v[(i + 1) % n]
        e = b - a
        w = p - a
        ee = float(e @ e)
        t = np.clip((w @ e) / ee, 0.0, 1.0) if ee > 0.0 else np.zeros(p.shape[0])
        diff = w - np.outer(t, e)
        d = np.minimum(d, np.einsum("ij,ij->i", diff, diff))
        # 偶奇規則 (辺が点の水平線をまたぐ回数)
        cond1 = p[:, 1] >= a[1]
        cond2 = p[:, 1] < b[1]
        cross = e[0] * w[:, 1] - e[1] * w[:, 0]
        c_all = (cond1 & cond2 & (cross > 0)) | (~cond1 & ~cond2 & (cross < 0))
        inside ^= c_all
    dist = np.sqrt(d)
    return np.where(inside, -dist, dist)


def circle_profile(radius: float, steps: int, z_center: float = 0.0, half: bool = False):
    """(r,z) の円弧。half=True なら下極から上極までの半円 (回転体の球用)。"""
    out = []
    if half:
        for i in range(steps + 1):
            phi = -0.5 * np.pi + np.pi * i / steps
            out.append((radius * np.cos(phi), z_center + radius * np.sin(phi)))
    else:
        for i in range(steps):
            phi = 2.0 * np.pi * i / steps
            out.append((radius * np.cos(phi), z_center + radius * np.sin(phi)))
    return out
