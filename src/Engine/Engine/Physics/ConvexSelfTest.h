//     しても、クック blob がバイト単位で一致すること。凸包はクックされて .rep の再生でも
//     使われるので、ここが割れると「同じシーンなのに機種でワールドハッシュが違う」になる
//   - 箱・四面体の頂点数 / 面数 / 稜線数がオイラーの多面体定理を満たすこと
//     (同一平面の三角形が統合されて箱が 6 面になること = 参照面クリップの品質の前提)
//   - 体積・重心・慣性テンソルが解析値と一致すること (非一様スケールを含む)
//   - 縮退入力 (点 / 線分 / 平面) が**箱へ落ちて必ず有効な形状を返す**こと。
//     「形状なし」に落ちると物体が世界をすり抜けるので、安全側は常に箱
//   - `.mcvx` blob が往復でビット同一なこと (フレッシュ生成とクックの等価性)
