// SSR (スクリーンスペース反射、M56d) のヘッドレス回帰テスト。GPU もウィンドウも要らない。
//
// SSR も HZB と同じで「絵を見ても壊れているか分からない」種類のパスで、間違っていても
// それらしい反射が出てしまう。CPU で機械的に固定できるのは階層トレースを支える
// 純関数 3 本なので、そこを全部ここで押さえる:
//
//   - `SsrCellAdvance` が **必ず前進する** こと。★セル境界のちょうど上に居る場合や
//     軸に平行な光線で増分 0 を返すと、光線が同じ場所で反復を使い切る。症状は
//     「反射が出ない」だけなので、絵からは永久に原因が追えない
//   - `SsrCellAdvance` が本当にセルの**外**へ着地させること (境界のわずかに先)
//   - `SsrReflWeight` が maxRoughness 以上で**厳密に 0**、0 で 1 を返すこと。
//     0 が厳密でないと「粗い面には 1 ビットも足さない」= golden 不変の根拠が消える
//   - `SsrReflWeight` の既定値 (0.6) が RT 反射 (M46h) の (0.4, 0.6) フェードと
//     完全に一致すること。SSR と RT 反射が同じ面で段差を作らないための約束
//   - `SsrEdgeFade` が画面の外で 0、中央で 1、端で単調に立ち上がること
